#!/usr/bin/env node

// Build the compact spell -> recipe-item and product required-level indexes
// used by Adventure Tracker. Inputs are Blizzard DB2 CSV exports from
// wago.tools for one WoW: Forever client build.

import fs from "node:fs";
import path from "node:path";

function argumentsByName(argv) {
  const values = {};
  for (let index = 2; index < argv.length; index += 2) {
    const name = argv[index];
    if (!name?.startsWith("--") || argv[index + 1] == null) {
      throw new Error(`Expected --name value, received ${name ?? "end of input"}`);
    }
    values[name.slice(2)] = argv[index + 1];
  }
  return values;
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (quoted) {
      if (char === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ",") {
      row.push(field);
      field = "";
    } else if (char === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += char;
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }
  return rows;
}

function objectsFromCsv(file) {
  const rows = parseCsv(fs.readFileSync(file, "utf8"));
  const headers = rows.shift();
  return rows.filter((row) => row.length > 1).map((row) => {
    const value = {};
    for (let index = 0; index < headers.length; index += 1) value[headers[index]] = row[index] ?? "";
    return value;
  });
}

function numericSort(a, b) {
  return a - b;
}

const options = argumentsByName(process.argv);
for (const required of ["catalog", "item-effect", "item-links", "item-sparse", "output", "build"]) {
  if (!options[required]) throw new Error(`Missing --${required}`);
}

const catalogText = fs.readFileSync(options.catalog, "utf8");
const recipes = [...catalogText.matchAll(/^\s+"(\d+);\d+;\d+;\d+;\d+;\d+;(\d+);/gm)].map((match) => ({
  productID: Number(match[1]),
  spellID: Number(match[2]),
}));
const recipeSpells = new Set(recipes.map((row) => row.spellID));
const products = new Set(recipes.map((row) => row.productID));

const spellByEffect = new Map();
for (const row of objectsFromCsv(options["item-effect"])) {
  const spellID = Number(row.SpellID);
  if (recipeSpells.has(spellID) && Number(row.TriggerType) === 6) spellByEffect.set(Number(row.ID), spellID);
}

const itemsBySpell = new Map();
for (const row of objectsFromCsv(options["item-links"])) {
  const spellID = spellByEffect.get(Number(row.ItemEffectID));
  if (!spellID) continue;
  const itemID = Number(row.ItemID);
  const items = itemsBySpell.get(spellID) ?? [];
  if (!items.includes(itemID)) items.push(itemID);
  itemsBySpell.set(spellID, items);
}

const requiredLevels = new Map();
for (const row of objectsFromCsv(options["item-sparse"])) {
  const itemID = Number(row.ID);
  const requiredLevel = Number(row.RequiredLevel);
  if (products.has(itemID) && requiredLevel > 0) requiredLevels.set(itemID, requiredLevel);
}

const lines = [
  "-- Adventure Tracker generated Blizzard client-data index.",
  `-- Source: WoW: Forever ${options.build} ItemEffect, ItemXItemEffect and ItemSparse DB2 tables.`,
  "-- Extracted from build-stamped client-table CSV exports; Blizzard game data is not relicensed.",
  "-- This compact file contains no QuestieDB records, coordinates, routes or map pins.",
  "-- GENERATED by tools/build_recipe_source_index.mjs. Do not edit by hand.",
  "local _, ns = ...",
  "ns.RecipeSourceIndexData = {",
  `  build = ${JSON.stringify(options.build)},`,
  "  recipeItems = {",
];
for (const spellID of [...itemsBySpell.keys()].sort(numericSort)) {
  const items = itemsBySpell.get(spellID).sort(numericSort);
  const value = items.length === 1 ? String(items[0]) : `{ ${items.join(", ")} }`;
  lines.push(`    [${spellID}] = ${value},`);
}
lines.push("  },", "  requiredLevels = {");
for (const itemID of [...requiredLevels.keys()].sort(numericSort)) {
  lines.push(`    [${itemID}] = ${requiredLevels.get(itemID)},`);
}
lines.push("  },", "}", "");

fs.mkdirSync(path.dirname(options.output), { recursive: true });
fs.writeFileSync(options.output, lines.join("\n"), "utf8");
process.stdout.write(
  `Wrote ${itemsBySpell.size} recipe-spell mappings and ${requiredLevels.size} required levels to ${options.output}\n`,
);
